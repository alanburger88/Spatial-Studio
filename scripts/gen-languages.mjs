// Generates packages/model/src/languages.data.ts from this Node's CLDR data (Intl), so runtime formatting is a plain
// table lookup that is identical in the browser and on the server. Re-run after changing the list: node scripts/gen-languages.mjs
import { writeFileSync } from 'node:fs';

// Left-to-right, Latin-script languages only (see reports/DECISIONS.md).
const CODES = ['es-US', 'es-ES', 'es-MX', 'fr-FR', 'fr-CA', 'pt-BR', 'pt-PT', 'de-DE', 'it-IT', 'nl-NL', 'af-ZA', 'zu-ZA', 'xh-ZA', 'st-ZA', 'tn-ZA', 'sw-KE',
  'en-GB', 'en-ZA', 'da-DK', 'sv-SE', 'nb-NO', 'fi-FI', 'is-IS', 'pl-PL', 'cs-CZ', 'sk-SK', 'hu-HU', 'ro-RO', 'hr-HR', 'sl-SI', 'et-EE', 'lv-LV', 'lt-LT',
  'tr-TR', 'id-ID', 'ms-MY', 'fil-PH', 'vi-VN', 'ca-ES', 'eu-ES', 'gl-ES', 'ga-IE', 'cy-GB', 'ha-NG', 'yo-NG', 'ig-NG', 'so-SO'];

const NBSP = /[  ]/g;
const out = [];
const skipped = [];
for (const code of CODES) {
  const lang = code.split('-')[0];
  if (!Intl.DateTimeFormat.supportedLocalesOf([code]).length || !Intl.DateTimeFormat.supportedLocalesOf([lang]).length) { skipped.push(code); continue; }
  const months = Array.from({ length: 12 }, (_, i) => new Intl.DateTimeFormat(code, { month: 'short', timeZone: 'UTC' }).format(new Date(Date.UTC(2026, i, 15))));
  const dparts = new Intl.DateTimeFormat(code, { year: 'numeric', month: 'short', day: 'numeric', timeZone: 'UTC' }).formatToParts(new Date(Date.UTC(2026, 10, 25)));
  const datePattern = dparts.map((p) => (p.type === 'day' ? '{d}' : p.type === 'month' ? '{m}' : p.type === 'year' ? '{y}' : p.type === 'literal' ? p.value : '')).join('').replace(NBSP, ' ');
  const nparts = new Intl.NumberFormat(code, { style: 'currency', currency: 'USD', currencyDisplay: 'narrowSymbol' }).formatToParts(1234567.89);
  const group = (nparts.find((p) => p.type === 'group')?.value ?? ',').replace(NBSP, ' ');
  const decimal = nparts.find((p) => p.type === 'decimal')?.value ?? '.';
  const ci = nparts.findIndex((p) => p.type === 'currency'), ii = nparts.findIndex((p) => p.type === 'integer');
  const currencyFirst = ci < ii;
  const gap = nparts.some((p) => p.type === 'literal' && /\s/.test(p.value)) ? ' ' : '';
  const name = new Intl.DisplayNames(['en'], { type: 'language' }).of(code);
  let endonym = name;
  try { endonym = new Intl.DisplayNames([code], { type: 'language' }).of(code) ?? name; } catch { /* keep English name */ }
  out.push({ code, name, endonym, months, datePattern, group, decimal, currencyFirst, gap });
}
const body = `// GENERATED by scripts/gen-languages.mjs from CLDR (Node ${process.versions.node}, ICU ${process.versions.icu}, CLDR ${process.versions.cldr}). Do not edit by hand.
export interface LanguageData { code: string; name: string; endonym: string; months: string[]; datePattern: string; group: string; decimal: string; currencyFirst: boolean; gap: string }
export const LANGUAGE_DATA: LanguageData[] = ${JSON.stringify(out, null, 1).replace(/\n\s+"/g, ' "').replace(/\[\s+"/g, '["').replace(/"\s+\]/g, '"]').replace(/\n\s*\}/g, ' }')};
`;
writeFileSync(new URL('../packages/model/src/languages.data.ts', import.meta.url), body);
console.log(`languages: ${out.length} written${skipped.length ? `, skipped (no CLDR data here): ${skipped.join(', ')}` : ''}`);
