export type HtmlStringKey = keyof typeof HTML_STRINGS;
export type HtmlStrings = Record<HtmlStringKey, string>;

/** English defaults overlaid with any caller-supplied (translated) strings; blank overrides are ignored. */
export function resolveHtmlStrings(overrides?: Partial<Record<HtmlStringKey, string>>): HtmlStrings {
  const out: Record<string, string> = { ...HTML_STRINGS };
  if (overrides) for (const k of Object.keys(HTML_STRINGS) as HtmlStringKey[]) if (typeof overrides[k] === 'string' && overrides[k] !== '') out[k] = overrides[k] as string;
  return out as HtmlStrings;
}

/** Replaces `{name}` placeholders (unknown placeholders are left as written). */
export function fmtString(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
