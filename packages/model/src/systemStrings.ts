export type SystemStringKey = keyof typeof SYSTEM_STRINGS;
export type SystemStrings = Record<SystemStringKey, string>;

/** String id of a system string, as used in `project.strings` and by the translation commands. */
export const systemStringId = (key: string): string => `@sys/${key}`;
export const SYSTEM_STRING_KEYS = Object.keys(SYSTEM_STRINGS) as SystemStringKey[];

/** English defaults overlaid with translated strings; blank overrides are ignored. */
export function resolveSystemStrings(overrides?: Partial<Record<string, string>> | null): SystemStrings {
  const out: Record<string, string> = { ...SYSTEM_STRINGS };
  if (overrides) for (const k of SYSTEM_STRING_KEYS) if (typeof overrides[k] === 'string' && overrides[k] !== '') out[k] = overrides[k] as string;
  return out as SystemStrings;
}

/** Replaces `{name}` placeholders (unknown placeholders are left as written). */
export function fmtString(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** One system string in the given (possibly partial) translated set, with placeholders filled. */
export function sysText(strings: Partial<Record<string, string>> | null | undefined, key: SystemStringKey, vars?: Record<string, string | number>): string {
  const o = strings?.[key];
  return fmtString(typeof o === 'string' && o !== '' ? o : SYSTEM_STRINGS[key], vars);
}
